"""Data models for LangGraph research agent."""

from typing import List, Dict, Any, Optional
from datetime import datetime
from pydantic import BaseModel, Field
from enum import Enum


class SearchResult(BaseModel):
    """Model for a single search result."""
    title: str = Field(description="Title of the search result")
    url: str = Field(description="URL of the search result")
    snippet: str = Field(description="Brief snippet or description")
    source: str = Field(description="Source of the result (web, arxiv, github, etc.)")
    timestamp: datetime = Field(default_factory=datetime.now)
    # Crawled content fields
    crawled_content: Optional[str] = Field(None, description="Full content from crawling")
    crawl_error: Optional[str] = Field(None, description="Error if crawling failed")
    crawl_metadata: Optional[Dict[str, Any]] = Field(None, description="Metadata from crawling")
    content_quality_score: Optional[float] = Field(None, description="Quality score of crawled content")


class ResearchPhase(str, Enum):
    """Phases of research process."""
    PLANNING = "planning"
    SEARCHING = "searching"
    CRAWLING = "crawling"
    ANALYZING = "analyzing"
    SYNTHESIZING = "synthesizing"
    COMPLETE = "complete"


class ResearchPlan(BaseModel):
    """Research plan generated by LLM."""
    main_query: str = Field(description="Main research query")
    sub_queries: List[str] = Field(description="Sub-queries to search for")
    search_strategy: str = Field(description="Strategy for conducting searches")
    expected_sources: List[str] = Field(description="Expected types of sources")


class ResearchAnalysis(BaseModel):
    """Analysis of search results."""
    key_findings: List[str] = Field(description="Key findings from search results")
    relevant_urls: List[str] = Field(description="Most relevant URLs")
    gaps_identified: List[str] = Field(description="Information gaps identified")
    confidence_score: float = Field(description="Confidence in findings (0-1)")


class ResearchReport(BaseModel):
    """Final research report in structured format."""
    query: str = Field(description="Original research query")
    summary: str = Field(description="Executive summary of findings")
    detailed_findings: List[Dict[str, str]] = Field(
        description="Detailed findings with sources",
        default_factory=list
    )
    code_examples: List[Dict[str, str]] = Field(
        description="Code examples if applicable",
        default_factory=list
    )
    recommendations: List[str] = Field(
        description="Recommendations based on research",
        default_factory=list
    )
    sources: List[Dict[str, str]] = Field(
        description="All sources used",
        default_factory=list
    )
    limitations: List[str] = Field(
        description="Limitations of the research",
        default_factory=list
    )
    confidence_score: float = Field(
        description="Overall confidence score (0-1)",
        default=0.0
    )
    metadata: Dict[str, Any] = Field(
        description="Additional metadata",
        default_factory=dict
    )


class ResearchState(BaseModel):
    """State for the research workflow."""
    # Input
    query: str = Field(description="Research query")
    research_type: str = Field(default="detailed", description="Type of research")
    max_search_results: int = Field(default=5, description="Max results per search")
    
    # Process tracking
    current_phase: ResearchPhase = Field(default=ResearchPhase.PLANNING)
    search_queries: List[str] = Field(default_factory=list)
    search_results: List[SearchResult] = Field(default_factory=list)
    
    # LLM outputs (all JSON)
    research_plan: Optional[ResearchPlan] = None
    analysis: Optional[ResearchAnalysis] = None
    final_report: Optional[ResearchReport] = None
    
    # Metadata
    start_time: datetime = Field(default_factory=datetime.now)
    end_time: Optional[datetime] = None
    total_cost: float = Field(default=0.0)
    total_tokens: int = Field(default=0)
    errors: List[str] = Field(default_factory=list)
    
    # Process dump settings
    dump_enabled: bool = Field(default=False)
    dump_path: Optional[str] = None
    
    # Crawling settings
    enable_crawling: bool = Field(default=True)
    crawl_limit: Optional[int] = Field(default=None, description="Maximum number of pages to crawl")
    crawl_metadata: Optional[Dict[str, Any]] = None
    arxiv_pdf_dir: Optional[str] = None
    
    def to_dict(self) -> Dict[str, Any]:
        """Convert state to dictionary."""
        return self.model_dump(exclude_none=True, mode='json')